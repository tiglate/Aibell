#!/usr/bin/env python3
"""Generates src/Aibell.Audio.Aac/ScaleFactorBandTables.cs from ISO/IEC 14496-3:2009 Tables 4.129 .. 4.141 (pdftotext -layout text).

Only the numeric swb_offset values for 1024/128-sample windows are copied; every table is checked for the declared band count and
for strictly increasing offsets ending at 1024 (long) or 128 (short).

Usage: generate-aac-bands.py <iso-text.txt> <output.cs>
"""
import re
import sys

# sampling_frequency_index -> (long table title number, short table title number)
LONG = {0: 140, 1: 140, 2: 138, 3: 129, 4: 129, 5: 131, 6: 136, 7: 136, 8: 134, 9: 134, 10: 134, 11: 132}
SHORT = {0: 141, 1: 141, 2: 139, 3: 130, 4: 130, 5: 130, 6: 137, 7: 137, 8: 135, 9: 135, 10: 135, 11: 133}


def block(lines, number):
    start = next(i for i, l in enumerate(lines) if re.match(rf"\s*Table 4\.{number} [–-] scalefactor bands", l))
    end = next(i for i in range(start + 1, len(lines)) if re.match(r"\s*Table 4\.\d+ [–-] ", lines[i]))
    return [re.sub(r"\s+", " ", l).strip() for l in lines[start:end]]


def parse(lines, number, long_window):
    text = block(lines, number)
    count = next(int(m.group(1)) for l in text if (m := re.match(r"num_swb_(?:long|short)_ (\d+)", l)))
    entries = {}
    frame = 1024 if long_window else 128
    for l in text:
        l = re.sub(r"\s*\([^)]*\)", "", l)
        if not re.fullmatch(r"\d+(?: \d+)*", l):
            continue
        numbers = [int(n) for n in l.split()]
        if len(numbers) % 2 == 1:
            # A trailing lone number is the frame length that closes the last band.
            if numbers[-1] == frame:
                entries[count] = frame
            numbers = numbers[:-1]
        for i in range(0, len(numbers), 2):
            entries.setdefault(numbers[i], numbers[i + 1])
    offsets = [entries[i] for i in range(count + 1)]
    if sorted(entries) != list(range(count + 1)) or offsets != sorted(set(offsets)) or offsets[0] != 0 or offsets[-1] != (1024 if long_window else 128):
        raise SystemExit(f"Table 4.{number}: bad offsets {offsets}")
    return offsets


def main():
    lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
    out = ["// <auto-generated>",
           "// Generated by scripts/generate-aac-bands.py from ISO/IEC 14496-3:2009, Tables 4.129 to 4.141 (numeric data only).",
           "// Index = sampling_frequency_index (0 = 96 kHz .. 11 = 8 kHz); each array is swb_offset with the frame length as last entry.",
           "// </auto-generated>",
           "namespace Aibell.Audio.Aac;", "", "internal static class ScaleFactorBandTables", "{"]
    for name, mapping, long_window in (("Long", LONG, True), ("Short", SHORT, False)):
        out.append(f"    public static readonly int[][] {name} =")
        out.append("    [")
        for index in range(12):
            offsets = parse(lines, mapping[index], long_window)
            out.append("        [" + ", ".join(map(str, offsets)) + "],")
        out.append("    ];")
        out.append("")
    out[-1] = "}"
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


main()
