#!/usr/bin/env python3
"""Generates src/Aibell.Audio.Aac/HuffmanTables.cs from the text of ISO/IEC 14496-3:2009 (pdftotext -layout output).

Source: Tables 4.A.1 (scalefactor codebook) and 4.A.2 .. 4.A.12 (spectrum codebooks 1 .. 11). The ISO document is not stored in the
repository; this script only copies the numeric (index, length, codeword) triples and refuses to write anything that is not a
complete prefix code of the expected size.

Usage: generate-aac-tables.py <iso-text.txt> <output.cs>
"""
import re
import sys

EXPECTED = [("ScaleFactor", "Table 4.A.1", 121)] + [
    (f"Spectrum{n}", f"Table 4.A.{n + 1}", size)
    for n, size in zip(range(1, 12), (81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289))]
ROW = re.compile(r"(?:^|\s)(\d+)\s+(\d+)\s+([0-9a-fA-F]+)(?=\s|$)")


def table_text(lines, title):
    start = next(i for i, l in enumerate(lines) if re.match(r"\s*" + re.escape(title) + r" [–-] ", l))
    end = next(i for i in range(start + 1, len(lines)) if re.match(r"\s*Table 4\.A\.\d+ [–-] ", lines[i]))
    return lines[start + 1:end]


def parse(block, size):
    entries = {}
    for line in block:
        # Rows hold two (index, length, codeword) triples side by side.
        matches = list(ROW.finditer(line))
        pos = 0
        triples = re.findall(r"(\d+)\s+(\d+)\s+([0-9a-fA-F]+)", line)
        if len(triples) > 2 or not triples:
            continue
        for index, length, code in triples:
            index, length = int(index), int(length)
            if index < size and 1 <= length <= 19 and index not in entries:
                entries[index] = (length, int(code, 16))
    return entries


def check(name, entries, size):
    if sorted(entries) != list(range(size)):
        missing = sorted(set(range(size)) - set(entries))
        raise SystemExit(f"{name}: expected {size} entries, missing {missing[:10]}")
    kraft = 0.0
    words = []
    for index in range(size):
        length, code = entries[index]
        if code >> length:
            raise SystemExit(f"{name}: codeword {index} does not fit its length")
        kraft += 2.0 ** -length
        words.append(format(code, f"0{length}b"))
    for i, a in enumerate(words):
        for j, b in enumerate(words):
            if i != j and b.startswith(a):
                raise SystemExit(f"{name}: codeword {i} is a prefix of {j}")
    if abs(kraft - 1.0) > 1e-12:
        print(f"note: {name} Kraft sum is {kraft!r} (not complete)", file=sys.stderr)


def main():
    lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
    out = ["// <auto-generated>",
           "// Generated by scripts/generate-aac-tables.py from ISO/IEC 14496-3:2009, Tables 4.A.1 to 4.A.12 (numeric data only).",
           "// Each entry is (codeword length in bits, codeword value); the index is the position in the array.",
           "// </auto-generated>",
           "namespace Aibell.Audio.Aac;", "", "internal static class HuffmanTables", "{"]
    for name, title, size in EXPECTED:
        entries = parse(table_text(lines, title), size)
        check(name, entries, size)
        out.append(f"    public static readonly (byte Length, uint Code)[] {name} =")
        out.append("    [")
        row = []
        for index in range(size):
            length, code = entries[index]
            row.append(f"({length}, 0x{code:x})")
            if len(row) == 8 or index == size - 1:
                out.append("        " + ", ".join(row) + ",")
                row = []
        out.append("    ];")
        out.append("")
    out[-1] = "}"
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


main()
