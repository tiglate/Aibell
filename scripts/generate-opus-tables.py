def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def initializer(path, name, occurrence=0):
    text = strip_comments(open(path, encoding="latin-1").read())
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*(?:\[[^\]]*\]\s*)+=\s*\{", re.S)
    matches = list(pattern.finditer(text))
    if len(matches) <= occurrence:
        sys.exit(f"{name} not found in {path}")
    start = matches[occurrence].end() - 1
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
    sys.exit(f"{name}: unterminated initializer")


def numbers(body):
    body = re.sub(r"QCONST(?:16|32)\(\s*([^,()]+?)\s*,\s*\d+\s*\)", r"\1", body)
    body = body.replace("{", " ").replace("}", " ")
    values = []
    for token in body.split(","):
        token = token.strip()
        if not token:
            continue
        if not token.lower().startswith("0x"):
            token = re.sub(r"(?<=[0-9.])[fFuUlL]+$", "", token)
        values.append(eval(token, {"__builtins__": {}}, CONSTANTS))
    return values


def csharp_literal(value, kind):
    if kind == "float":
        return repr(float(value)) + "f"
    return str(int(value))


def emit(out, name, kind, values, expected):
    if len(values) != expected:
        sys.exit(f"{name}: expected {expected} values, found {len(values)}")
    ctype = {"byte": "byte", "short": "short", "int": "int", "float": "float", "sbyte": "sbyte"}[kind]
    rows = []
    for i in range(0, len(values), 12):
        rows.append("        " + ", ".join(csharp_literal(v, kind) for v in values[i:i + 12]) + ",")
    if kind == "byte":
        out.append(f"    public static ReadOnlySpan<byte> {name} => [\n" + "\n".join(rows) + "\n    ];\n")
    else:
        out.append(f"    public static readonly {ctype}[] {name} =\n    [\n" + "\n".join(rows) + "\n    ];\n")


