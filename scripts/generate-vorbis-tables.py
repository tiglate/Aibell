#!/usr/bin/env python3
"""Generates src/Aibell.Audio.Vorbis/Floor1Table.cs from the text of the Vorbis I specification (section 10.1, floor1_inverse_dB_table).

Usage: generate-vorbis-tables.py <Vorbis_I_spec.html or a text rendering of it> <output .cs>

The 256 values are extracted by pattern, never typed. The script refuses input that does not yield exactly 256 strictly increasing numbers
whose neighbour ratios are a constant 140/256 dB step (the property the table is built on).
"""
import html
import math
import re
import sys


def main(source, target):
    text = open(source, encoding="latin-1").read()
    text = re.sub(r"<script.*?</script>", "", text, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    text = html.unescape(text).replace("\xa0", " ")
    start = text.index("top to bottom")
    end = text.index("Embedding Vorbis into an Ogg stream", start)
    values = re.findall(r"\d+\.\d*(?:e[-+]?\d+)?", text[start:end])
    numbers = [float(v) for v in values]
    if len(numbers) != 256:
        sys.exit(f"expected 256 values, found {len(numbers)}")
    if any(b <= a for a, b in zip(numbers, numbers[1:])):
        sys.exit("the table must be strictly increasing")
    for a, b in zip(numbers, numbers[1:]):
        step_db = 20 * math.log10(b / a)
        if abs(step_db - 140 / 256) > 1e-4:
            sys.exit(f"neighbour step of {step_db} dB is not the expected 140/256 dB")
    if abs(numbers[-1] - 1.0) > 1e-12:
        sys.exit("the last value must be 1")
    rows = []
    for i in range(0, 256, 4):
        rows.append("        " + ", ".join(f"{values[j].rstrip('.') if values[j].endswith('.') else values[j]}f" for j in range(i, i + 4)) + ",")
    with open(target, "w", encoding="utf-8", newline="\n") as out:
        out.write("// <auto-generated>Produced by scripts/generate-vorbis-tables.py from Vorbis I specification section 10.1. Do not edit.</auto-generated>\n")
        out.write("namespace Aibell.Audio.Vorbis;\n\n")
        out.write("internal static class Floor1Table\n{\n")
        out.write("    /// <summary>floor1_inverse_dB_table: maps a floor value 0..255 to a linear amplitude (steps of 140/256 dB ending at 1).</summary>\n")
        out.write("    public static readonly float[] InverseDb =\n    [\n")
        out.write("\n".join(rows) + "\n    ];\n}\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
